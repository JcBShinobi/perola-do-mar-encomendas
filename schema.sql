-- Sequência que gera o número amigável da encomenda (#0001, #0002, ...)
create sequence if not exists public.encomendas_numero_seq;

create table if not exists public.encomendas (
    id bigint generated by default as identity primary key,
    numero_encomenda integer not null default nextval('public.encomendas_numero_seq'),
    nome_cliente text not null,
    telefone text,
    produtos text,
    data_levantamento date not null,
    hora_levantamento time,
    estado_encomenda text not null default 'Pendente'
        check (estado_encomenda in ('Pendente', 'Em Produção', 'Pronta', 'Entregue')),
    estado_pagamento text not null default 'Por Pagar'
        check (estado_pagamento in ('Por Pagar', 'Pago')),
    observacoes text,
    funcionario text,
    created_at timestamp with time zone not null default now()
);

-- Se a tabela já existia sem número automático, garante o valor por omissão.
alter table public.encomendas
    alter column numero_encomenda
    set default nextval('public.encomendas_numero_seq');

-- Evita números repetidos.
create unique index if not exists encomendas_numero_encomenda_key
    on public.encomendas (numero_encomenda);

-- Acelera os filtros por dia/hora usados no painel de gestão.
create index if not exists encomendas_data_levantamento_idx
    on public.encomendas (data_levantamento, hora_levantamento);

-- ============================================================
-- Acesso com a chave "anon".
-- A chave fica apenas no servidor (st.secrets), nunca no browser.
-- ============================================================
alter table public.encomendas enable row level security;

drop policy if exists "encomendas_acesso_app" on public.encomendas;
create policy "encomendas_acesso_app"
    on public.encomendas
    for all
    to anon, authenticated
    using (true)
    with check (true);

grant usage, select on sequence public.encomendas_numero_seq to anon, authenticated;
grant select, insert, update, delete on table public.encomendas
    to anon, authenticated;
