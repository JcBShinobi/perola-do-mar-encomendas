"""Pérola do Mar — Gestão de encomendas de Natal (Streamlit + Supabase).

Antes de arrancar a aplicação, crie a tabela no Supabase (SQL Editor → Run).
O script completo, incluindo permissões, está em `schema.sql`.

    create sequence if not exists public.encomendas_numero_seq;

    create table if not exists public.encomendas (
        id bigint generated by default as identity primary key,
        numero_encomenda integer not null default nextval('public.encomendas_numero_seq'),
        nome_cliente text not null,
        telefone text,
        produtos text,
        produtos_padaria text,
        produtos_pastelaria text,
        produtos_cozinha text,
        padaria_pronta boolean not null default false,
        pastelaria_pronta boolean not null default false,
        cozinha_pronta boolean not null default false,
        data_levantamento date not null,
        hora_levantamento time,
        estado_encomenda text not null default 'Pendente'
            check (estado_encomenda in ('Pendente', 'Em Produção', 'Pronta', 'Entregue')),
        estado_separacao text not null default 'Não separado'
            check (estado_separacao in ('Não separado', 'A separar', 'Separado', 'Entregue')),
        observacoes text,
        funcionario text,
        created_at timestamp with time zone not null default now()
    );

    alter table public.encomendas enable row level security;
    create policy "encomendas_acesso_app" on public.encomendas
        for all to anon, authenticated using (true) with check (true);

Configure depois `.streamlit/secrets.toml` com SUPABASE_URL e SUPABASE_KEY.

A app começa num ecrã sem autenticação para escolher o perfil **Geral**
(gestão completa) ou **Fabrico** (produção por área).
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

import streamlit as st

import db
import ui
from views import fabrico, gestao, nova_encomenda, separacao

INTERVALO_ATUALIZACAO = "5s"
PERFIS = ("Geral", "Fabrico")

st.set_page_config(
    page_title="Pérola do Mar · Encomendas de Natal",
    page_icon="🎄",
    layout="wide",
)


def _ajuda_configuracao() -> None:
    """Instruções mostradas quando faltam as credenciais do Supabase."""
    with st.expander("Como configurar as credenciais", expanded=True):
        st.markdown(
            "Crie o ficheiro `.streamlit/secrets.toml` na raiz do projeto "
            "(ou defina os secrets no Streamlit Cloud) com:"
        )
        st.code(
            'SUPABASE_URL = "https://xxxxxxxxxxxx.supabase.co"\n'
            'SUPABASE_KEY = "eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9..."\n',
            language="toml",
        )
        st.markdown(
            "No Supabase: **Project Settings → API** → copie o **Project URL** e a chave **anon public**."
        )


def _ajuda_sql() -> None:
    """Mostra o script SQL para desbloquear a configuração inicial."""
    with st.expander("Criar a tabela no Supabase", expanded=True):
        st.markdown(
            "Abra o **SQL Editor** do Supabase, cole o script abaixo e clique em **Run**."
        )
        caminho = Path(__file__).with_name("schema.sql")
        try:
            st.code(caminho.read_text(encoding="utf-8"), language="sql")
        except OSError:
            st.warning("Não foi possível ler `schema.sql`. Consulte o ficheiro no projeto.")


def _verificar_ligacao() -> None:
    """Verifica a ligação uma vez por sessão, mostrando ajuda se falhar."""
    if st.session_state.get("ligacao_ok"):
        return
    try:
        db.verificar_ligacao()
    except db.ErroConfiguracao as exc:
        st.error(f"⚠️ Configuração em falta: {exc}")
        _ajuda_configuracao()
        st.stop()
    except db.ErroBaseDados as exc:
        st.error(f"⚠️ Não foi possível ligar à base de dados. {exc}")
        _ajuda_sql()
        if st.button("Tentar novamente", type="primary", key="tentar_ligacao"):
            st.session_state.pop("ligacao_ok", None)
            st.rerun()
        st.stop()
    st.session_state["ligacao_ok"] = True


def _assinatura_local() -> str:
    """Fallback durante um redeploy em que o módulo db ainda está em cache."""
    cliente = db.get_client()
    resposta = (
        cliente.table(db.TABELA)
        .select("id,xmin")
        .order("id")
        .limit(getattr(db, "LIMITE_CONSULTA", 1000))
        .execute()
    )
    linhas = sorted(
        list(resposta.data or []),
        key=lambda linha: int(linha.get("id") or 0),
    )
    payload = json.dumps(
        linhas,
        sort_keys=True,
        ensure_ascii=False,
        default=str,
    )
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


@st.fragment(run_every=INTERVALO_ATUALIZACAO)
def _vigiar_encomendas() -> None:
    """Recarrega a app quando outra sessão cria, edita ou elimina encomendas."""
    # Mantém o fragmento registado mesmo sem conteúdo visível.
    st.markdown(
        "<span style='display:none' data-refresh-watch='1'></span>",
        unsafe_allow_html=True,
    )

    try:
        assinatura = db.assinatura_encomendas()
    except AttributeError:
        # O Streamlit Cloud pode manter o módulo db anterior em cache durante
        # o redeploy; o fallback evita que a app fique indisponível.
        try:
            assinatura = _assinatura_local()
        except Exception:
            return
    except db.ErroBaseDados:
        # A app principal já apresenta o erro de ligação; tentamos novamente
        # na próxima verificação automática.
        return

    anterior = st.session_state.get(ui.CHAVE_ASSINATURA)
    if anterior == assinatura:
        return

    st.session_state[ui.CHAVE_ASSINATURA] = assinatura
    if anterior is not None:
        st.rerun(scope="app")


def _selecionar_perfil(perfil: str) -> None:
    st.session_state["perfil"] = perfil


def _trocar_utilizador() -> None:
    # O próximo funcionário deve começar sem dados do utilizador anterior.
    for chave in list(st.session_state):
        if chave.startswith("nc_"):
            st.session_state.pop(chave, None)

    for chave in (
        "perfil",
        "abas_principais",
        "abas_fabrico",
        "encomenda_edicao",
        "encomenda_apagar",
        "form_versao",
        "ultima_encomenda",
        "fechar_ultima",
        "gestao_modo_data",
        "gestao_dia",
        "gestao_pesquisa",
        "gestao_assinatura",
        "gestao_pagina",
        "mensagens",
    ):
        st.session_state.pop(chave, None)


def _acoes_topo() -> None:
    """Troca de utilizador e teste de ligação, discretos no topo."""
    with st.container(
        horizontal=True,
        horizontal_alignment="left",
        gap="small",
    ):
        st.button(
            " ",
            key="trocar_utilizador",
            type="tertiary",
            icon=":material/switch_account:",
            help="Trocar utilizador",
            on_click=_trocar_utilizador,
        )
        if st.button(
            " ",
            key="testar_ligacao",
            type="tertiary",
            icon=":material/wifi:",
            help="Testar ligação ao Supabase",
        ):
            try:
                db.verificar_ligacao()
                st.toast("Ligação ao Supabase a funcionar.")
            except db.ErroBaseDados as exc:
                st.error(str(exc))


def _ecra_inicial() -> None:
    """Ecrã sem autenticação para escolher o perfil de trabalho."""
    with st.container(key="ecra_inicial"):
        with st.container(
            horizontal=True,
            horizontal_alignment="center",
            gap="large",
        ):
            st.button(
                "Geral",
                key="perfil_geral",
                type="primary",
                on_click=_selecionar_perfil,
                args=("Geral",),
            )
            st.button(
                "Fabrico",
                key="perfil_fabrico",
                type="secondary",
                on_click=_selecionar_perfil,
                args=("Fabrico",),
            )


def _vista_geral() -> None:
    encomendas_organizacao, erro_organizacao = separacao.carregar()

    (
        aba_nova,
        aba_gestao,
        aba_encomendas,
        aba_a_separar,
        aba_separado,
        aba_entregue,
    ) = st.tabs(
        [
            "🎄 Nova encomenda",
            "📋 Consulta e gestão",
            "📦 Encomendas",
            "🧺 A separar",
            "✅ Separado",
            "🚚 Entregue",
        ],
        default="🎄 Nova encomenda",
        key="abas_principais",
        on_change="rerun",
    )
    with aba_nova:
        nova_encomenda.render()
    with aba_gestao:
        gestao.render()
    with aba_encomendas:
        separacao.render("todas", encomendas_organizacao, erro_organizacao)
    with aba_a_separar:
        separacao.render("a_separar", encomendas_organizacao, erro_organizacao)
    with aba_separado:
        separacao.render("separado", encomendas_organizacao, erro_organizacao)
    with aba_entregue:
        separacao.render("entregue", encomendas_organizacao, erro_organizacao)


def _vista_fabrico() -> None:
    encomendas, erro = fabrico.carregar()
    aba_padaria, aba_pastelaria, aba_cozinha = st.tabs(
        ["🥖 Padaria", "🧁 Pastelaria", "🍲 Cozinha"],
        default="🥖 Padaria",
        key="abas_fabrico",
        on_change="rerun",
    )
    with aba_padaria:
        fabrico.render("padaria", encomendas, erro)
    with aba_pastelaria:
        fabrico.render("pastelaria", encomendas, erro)
    with aba_cozinha:
        fabrico.render("cozinha", encomendas, erro)


def main() -> None:
    ui.inject_css()

    perfil = st.session_state.get("perfil")
    if perfil not in PERFIS:
        _ecra_inicial()
        return

    _verificar_ligacao()
    _vigiar_encomendas()
    _acoes_topo()
    ui.mostrar_flash()

    if perfil == "Fabrico":
        _vista_fabrico()
    else:
        _vista_geral()


main()
