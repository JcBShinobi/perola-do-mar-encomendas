"""Pérola do Mar — Gestão de encomendas de Natal (Streamlit + Supabase).

Antes de arrancar a aplicação, crie a tabela no Supabase (SQL Editor → Run).
O script completo, incluindo permissões, está em `schema.sql`.

    create sequence if not exists public.encomendas_numero_seq;

    create table if not exists public.encomendas (
        id bigint generated by default as identity primary key,
        numero_encomenda integer not null default nextval('public.encomendas_numero_seq'),
        nome_cliente text not null,
        telefone text,
        produtos text,
        data_levantamento date not null,
        hora_levantamento time,
        estado_encomenda text not null default 'Pendente'
            check (estado_encomenda in ('Pendente', 'Em Produção', 'Pronta', 'Entregue')),
        estado_pagamento text not null default 'Por Pagar'
            check (estado_pagamento in ('Por Pagar', 'Pago')),
        observacoes text,
        funcionario text,
        created_at timestamp with time zone not null default now()
    );

    alter table public.encomendas enable row level security;
    create policy "encomendas_acesso_app" on public.encomendas
        for all to anon, authenticated using (true) with check (true);

Configure depois `.streamlit/secrets.toml` com SUPABASE_URL e SUPABASE_KEY.
"""
from __future__ import annotations

from pathlib import Path

import streamlit as st

import db
import ui
from views import gestao, nova_encomenda

st.set_page_config(
    page_title="Pérola do Mar · Encomendas de Natal",
    page_icon="🎄",
    layout="wide",
    initial_sidebar_state="collapsed",
)


def _ajuda_configuracao() -> None:
    """Instruções mostradas quando faltam as credenciais do Supabase."""
    with st.expander("Como configurar as credenciais", expanded=True):
        st.markdown(
            "Crie o ficheiro `.streamlit/secrets.toml` na raiz do projeto "
            "(ou defina os secrets no Streamlit Cloud) com:"
        )
        st.code(
            'SUPABASE_URL = "https://xxxxxxxxxxxx.supabase.co"\n'
            'SUPABASE_KEY = "eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9..."\n',
            language="toml",
        )
        st.markdown(
            "No Supabase: **Project Settings → API** → copie o **Project URL** e a chave **anon public**."
        )


def _ajuda_sql() -> None:
    """Mostra o script SQL para desbloquear a configuração inicial."""
    with st.expander("Criar a tabela no Supabase", expanded=True):
        st.markdown(
            "Abra o **SQL Editor** do Supabase, cole o script abaixo e clique em **Run**."
        )
        caminho = Path(__file__).with_name("schema.sql")
        try:
            st.code(caminho.read_text(encoding="utf-8"), language="sql")
        except OSError:
            st.warning("Não foi possível ler `schema.sql`. Consulte o ficheiro no projeto.")


def _verificar_ligacao() -> None:
    """Verifica a ligação uma vez por sessão, mostrando ajuda se falhar."""
    if st.session_state.get("ligacao_ok"):
        return
    try:
        db.verificar_ligacao()
    except db.ErroConfiguracao as exc:
        st.error(f"⚠️ Configuração em falta: {exc}")
        _ajuda_configuracao()
        st.stop()
    except db.ErroBaseDados as exc:
        st.error(f"⚠️ Não foi possível ligar à base de dados. {exc}")
        _ajuda_sql()
        if st.button("Tentar novamente", type="primary", key="tentar_ligacao"):
            st.session_state.pop("ligacao_ok", None)
            st.rerun()
        st.stop()
    st.session_state["ligacao_ok"] = True


def _barra_lateral() -> None:
    with st.sidebar:
        st.markdown("### 🎄 Pérola do Mar")
        st.caption("Padaria & Cafetaria · Encomendas de Natal")
        st.divider()
        st.markdown("**Ligação à base de dados**")
        st.caption("🟢 Supabase configurado")
        if st.button("Testar ligação", key="testar_ligacao"):
            try:
                db.verificar_ligacao()
                st.toast("Ligação ao Supabase a funcionar.")
            except db.ErroBaseDados as exc:
                st.error(str(exc))
        st.divider()
        st.caption(
            "Os dados ficam guardados no Supabase, por isso a equipa pode consultar "
            "e atualizar encomendas a partir de qualquer dispositivo."
        )


def main() -> None:
    ui.inject_css()
    ui.cabecalho()
    _verificar_ligacao()
    ui.mostrar_flash()
    _barra_lateral()

    aba_nova, aba_gestao = st.tabs(["🎄 Nova encomenda", "📋 Consulta e gestão"])
    with aba_nova:
        nova_encomenda.render()
    with aba_gestao:
        gestao.render()


main()
